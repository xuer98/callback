/**
 * Throws on a slug that is not a seeded problem or a name outside the
 * vocabulary of the imported listings.
 */
export function checkProblemTopics(
  slugs: ReadonlySet<string>,
  vocabulary: ReadonlySet<string>,
): void {
  for (const [slug, topics] of Object.entries(problemTopics)) {
    if (!slugs.has(slug)) {
      throw new Error(`seed-topics: no problem has the slug "${slug}"`);
    }
    for (const topic of topics) {
      if (!vocabulary.has(topic)) {
        throw new Error(
          `seed-topics: "${slug}" has an unknown topic "${topic}"`,
        );
      }
    }
  }
}
